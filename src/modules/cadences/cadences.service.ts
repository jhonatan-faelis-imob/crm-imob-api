import { BadRequestException, Injectable, NotFoundException } from '@nestjs/common'
import { Prisma } from '@prisma/client'
import { assertCanViewLead, type VisibilityUser } from '../../common/utils/lead-visibility'
import { normalizeStageName } from '../../common/utils/stage'
import { PrismaService } from '../../prisma/prisma.service'
import { cadenceDueDate, cadenceTitle } from './cadence-date'
import { MAX_STEPS_PER_STAGE, MAX_TASKS_PER_APPLY } from './cadence-limits'
import { DEFAULT_CADENCE_STEPS } from './default-steps'
import { ReorderStepsDto } from './dto/cadence-actions.dto'
import { CreateCadenceStepDto, UpdateCadenceStepDto } from './dto/cadence-step.dto'

export { MAX_STEPS_PER_STAGE } from './cadence-limits'
const CANCELLED_NOTE = 'Cancelada automaticamente: o lead mudou de etapa'

export interface StageChangeInput {
  organizationId: string
  lead: { id: string; name: string; ownerId: string | null }
  fromStageId: string | null
  // null = o lead saiu do funil (perdido): só cancela, não cria nada
  toStageId: string | null
  actorId: string
}

export interface CadenceResult {
  created: { id: string; title: string; type: string; dueDate: Date }[]
  cancelled: number
}

type CadenceStepRow = Prisma.StageCadenceStepGetPayload<object>

// A ordem é a que o gerente arrasta na tela; offsetDays só desempata
const STEP_ORDER: Prisma.StageCadenceStepOrderByWithRelationInput[] = [{ orderIndex: 'asc' }, { offsetDays: 'asc' }]
const ASSIGNEE_SELECT = { select: { id: true, name: true, avatarUrl: true } } as const

function taskFromStep(
  step: CadenceStepRow,
  lead: { id: string; name: string; ownerId: string | null },
  context: { organizationId: string; stageId: string; actorId: string; now: Date },
): Prisma.TaskCreateManyInput {
  return {
    organizationId: context.organizationId,
    leadId: lead.id,
    assignedTo: lead.ownerId ?? context.actorId,
    createdBy: context.actorId,
    autoGenerated: true,
    cadenceStageId: context.stageId,
    cadenceStepId: step.id,
    title: cadenceTitle(step.title, lead.name),
    description: step.description,
    type: step.type,
    priority: step.priority,
    dueDate: cadenceDueDate(step, context.now),
  }
}

@Injectable()
export class CadencesService {
  constructor(private prisma: PrismaService) {}

  async findAll(organizationId: string) {
    await this.ensureDefaults(organizationId)
    return this.prisma.funnelStage.findMany({
      where: { organizationId },
      orderBy: { orderIndex: 'asc' },
      select: {
        id: true,
        name: true,
        color: true,
        orderIndex: true,
        cadenceSteps: { orderBy: STEP_ORDER },
      },
    })
  }

  async createStep(organizationId: string, dto: CreateCadenceStepDto) {
    const stage = await this.findStage(organizationId, dto.funnelStageId)

    const { _count, _max } = await this.prisma.stageCadenceStep.aggregate({
      where: { organizationId, funnelStageId: stage.id },
      _count: true,
      _max: { orderIndex: true },
    })
    if (_count >= MAX_STEPS_PER_STAGE) {
      throw new BadRequestException(`Cada etapa aceita no máximo ${MAX_STEPS_PER_STAGE} passos`)
    }

    return this.prisma.stageCadenceStep.create({
      data: {
        ...dto,
        description: dto.description?.trim() || null,
        organizationId,
        // Passo novo entra no fim da lista da etapa
        orderIndex: dto.orderIndex ?? (_max.orderIndex ?? -1) + 1,
      },
    })
  }

  async updateStep(organizationId: string, id: string, dto: UpdateCadenceStepDto) {
    await this.findStep(organizationId, id)
    return this.prisma.stageCadenceStep.update({
      where: { id },
      data: {
        ...dto,
        ...(dto.description !== undefined && { description: dto.description.trim() || null }),
      },
    })
  }

  async removeStep(organizationId: string, id: string) {
    await this.findStep(organizationId, id)
    // Tarefas já criadas guardam o id do passo sem chave estrangeira e continuam como estão
    await this.prisma.stageCadenceStep.delete({ where: { id } })
    return { id }
  }

  async reorderSteps(organizationId: string, { stageId, orderedIds }: ReorderStepsDto) {
    await this.findStage(organizationId, stageId)
    const steps = await this.prisma.stageCadenceStep.findMany({
      where: { organizationId, funnelStageId: stageId },
      select: { id: true },
    })

    const stageIds = new Set(steps.map((step) => step.id))
    const isSameSet =
      new Set(orderedIds).size === orderedIds.length &&
      orderedIds.length === stageIds.size &&
      orderedIds.every((id) => stageIds.has(id))
    if (!isSameSet) throw new BadRequestException('A lista precisa ter exatamente os passos desta etapa')

    await this.prisma.$transaction(
      orderedIds.map((id, index) => this.prisma.stageCadenceStep.update({ where: { id }, data: { orderIndex: index } })),
    )
    return this.prisma.stageCadenceStep.findMany({
      where: { organizationId, funnelStageId: stageId },
      orderBy: STEP_ORDER,
    })
  }

  // Etapa atual do lead, os passos ativos dela e as tarefas automáticas que ela criou (qualquer status)
  async findForLead(organizationId: string, leadId: string, user: VisibilityUser) {
    const lead = await this.findVisibleLead(organizationId, leadId, user)
    await this.ensureDefaults(organizationId)

    if (!lead.funnelStage) return { stage: null, steps: [], tasks: [] }

    const [steps, tasks] = await Promise.all([
      this.prisma.stageCadenceStep.findMany({
        where: { organizationId, funnelStageId: lead.funnelStage.id, active: true },
        orderBy: STEP_ORDER,
      }),
      this.prisma.task.findMany({
        where: { organizationId, leadId, autoGenerated: true, cadenceStageId: lead.funnelStage.id },
        include: { assignee: ASSIGNEE_SELECT, lead: { select: { id: true, name: true } } },
        orderBy: { dueDate: 'asc' },
      }),
    ])

    const { id, name, color } = lead.funnelStage
    return { stage: { id, name, color }, steps, tasks }
  }

  // Cria só os passos da etapa atual que não têm tarefa pendente; não cancela nada
  async reapplyForLead(organizationId: string, leadId: string, user: VisibilityUser) {
    const lead = await this.findVisibleLead(organizationId, leadId, user)
    if (!lead.funnelStageId) return { created: [] }
    await this.ensureDefaults(organizationId)

    const { created } = await this.prisma.$transaction((tx) =>
      this.applyOnStageChange(tx, {
        organizationId,
        lead,
        fromStageId: lead.funnelStageId,
        toStageId: lead.funnelStageId,
        actorId: user.id,
      }),
    )
    return { created }
  }

  async applyToExistingLeads(organizationId: string, stageId: string, dryRun: boolean, actorId: string) {
    await this.findStage(organizationId, stageId)

    if (dryRun) {
      const plan = await this.planExisting(this.prisma, organizationId, stageId, actorId)
      return { leads: plan.leads, tasksToCreate: plan.data.length }
    }

    // Recalcula dentro da transação: entre a prévia e a confirmação, alguém pode ter mexido
    return this.prisma.$transaction(async (tx) => {
      const plan = await this.planExisting(tx, organizationId, stageId, actorId)
      const { count } = plan.data.length ? await tx.task.createMany({ data: plan.data }) : { count: 0 }
      return { leads: plan.leads, tasksToCreate: plan.data.length, created: count }
    }, { timeout: 20_000 })
  }

  // Organização sem nenhum passo recebe os padrão. Chamado também antes de mudar etapa,
  // para a cadência valer mesmo que ninguém tenha aberto /cadencias
  async ensureDefaults(organizationId: string) {
    if (await this.prisma.stageCadenceStep.count({ where: { organizationId } })) return

    await this.prisma.$transaction(async (tx) => {
      // Sem índice único, duas chamadas simultâneas criariam os padrão em dobro
      await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${`cadences:${organizationId}`}))`
      if (await tx.stageCadenceStep.count({ where: { organizationId } })) return

      const stages = await tx.funnelStage.findMany({ where: { organizationId }, select: { id: true, name: true } })
      const stageByName = new Map(stages.map((stage) => [normalizeStageName(stage.name), stage.id]))

      const data = DEFAULT_CADENCE_STEPS.flatMap((step, index) => {
        const funnelStageId = stageByName.get(step.stage)
        if (!funnelStageId) return []
        return [{
          organizationId,
          funnelStageId,
          title: step.title,
          type: step.type,
          offsetDays: step.offsetDays,
          orderIndex: index,
        }]
      })
      if (data.length) await tx.stageCadenceStep.createMany({ data })
    })
  }

  // Roda dentro da mesma transação que grava o histórico de etapas
  async applyOnStageChange(tx: Prisma.TransactionClient, input: StageChangeInput): Promise<CadenceResult> {
    const { organizationId, lead, fromStageId, toStageId, actorId } = input

    // Só tarefas automáticas e pendentes: concluídas e manuais nunca são tocadas
    const cancelled = fromStageId !== toStageId
      ? await tx.task.updateMany({
          where: {
            organizationId,
            leadId: lead.id,
            status: 'pendente',
            autoGenerated: true,
            ...(toStageId && { OR: [{ cadenceStageId: null }, { cadenceStageId: { not: toStageId } }] }),
          },
          data: { status: 'cancelada', completionNotes: CANCELLED_NOTE },
        })
      : { count: 0 }

    if (!toStageId) return { created: [], cancelled: cancelled.count }

    const steps = await tx.stageCadenceStep.findMany({
      where: { organizationId, funnelStageId: toStageId, active: true },
      orderBy: STEP_ORDER,
    })
    if (!steps.length) return { created: [], cancelled: cancelled.count }

    const pending = await tx.task.findMany({
      where: {
        organizationId,
        leadId: lead.id,
        status: 'pendente',
        cadenceStepId: { in: steps.map((step) => step.id) },
      },
      select: { cadenceStepId: true },
    })
    const alreadyPending = new Set(pending.map((task) => task.cadenceStepId))

    const context = { organizationId, stageId: toStageId, actorId, now: new Date() }
    const data = steps
      .filter((step) => !alreadyPending.has(step.id))
      .map((step) => taskFromStep(step, lead, context))

    const created = data.length
      ? await tx.task.createManyAndReturn({
          data,
          select: { id: true, title: true, type: true, dueDate: true },
        })
      : []

    return { created, cancelled: cancelled.count }
  }

  // Leads ativos da etapa, com dono, sem tarefa pendente daquele passo. Acima do limite, nada é gravado
  private async planExisting(db: Prisma.TransactionClient, organizationId: string, stageId: string, actorId: string) {
    const steps = await db.stageCadenceStep.findMany({
      where: { organizationId, funnelStageId: stageId, active: true },
      orderBy: STEP_ORDER,
    })
    if (!steps.length) return { leads: 0, data: [] }

    const [leads, pending] = await Promise.all([
      db.lead.findMany({
        where: { organizationId, funnelStageId: stageId, active: true, ownerId: { not: null } },
        select: { id: true, name: true, ownerId: true },
      }),
      db.task.findMany({
        where: { organizationId, status: 'pendente', cadenceStepId: { in: steps.map((step) => step.id) } },
        select: { leadId: true, cadenceStepId: true },
      }),
    ])
    const pendingKeys = new Set(pending.map((task) => `${task.leadId}:${task.cadenceStepId}`))

    const context = { organizationId, stageId, actorId, now: new Date() }
    const leadIds = new Set<string>()
    const data: Prisma.TaskCreateManyInput[] = []
    for (const lead of leads) {
      for (const step of steps) {
        if (pendingKeys.has(`${lead.id}:${step.id}`)) continue
        data.push(taskFromStep(step, lead, context))
        leadIds.add(lead.id)
      }
    }

    if (data.length > MAX_TASKS_PER_APPLY) {
      throw new BadRequestException('Muitas tarefas de uma vez. Aplique por partes.')
    }
    return { leads: leadIds.size, data }
  }

  private async findVisibleLead(organizationId: string, leadId: string, user: VisibilityUser) {
    const lead = await this.prisma.lead.findFirst({
      where: { id: leadId, organizationId, active: true },
      select: {
        id: true,
        name: true,
        ownerId: true,
        teamId: true,
        funnelStageId: true,
        funnelStage: { select: { id: true, name: true, color: true } },
      },
    })
    if (!lead) throw new NotFoundException('Lead não encontrado')
    assertCanViewLead(lead, user)
    return lead
  }

  private async findStage(organizationId: string, stageId: string) {
    const stage = await this.prisma.funnelStage.findFirst({ where: { id: stageId, organizationId } })
    if (!stage) throw new NotFoundException('Etapa não encontrada')
    return stage
  }

  private async findStep(organizationId: string, id: string) {
    const step = await this.prisma.stageCadenceStep.findFirst({ where: { id, organizationId } })
    if (!step) throw new NotFoundException('Passo não encontrado')
    return step
  }
}
