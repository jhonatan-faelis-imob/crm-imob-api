import { Prisma } from '@prisma/client'
import { PrismaService } from '../../prisma/prisma.service'
import { CadencesService } from './cadences.service'

type CreatedTask = { title: string; assignedTo: string; cadenceStepId: string; dueDate: Date }

function step(id: string, overrides: Partial<{ title: string; offsetDays: number }> = {}) {
  return {
    id,
    title: overrides.title ?? 'Ligar para {{primeiro_nome}}',
    description: null,
    type: 'ligacao',
    priority: 'media',
    offsetDays: overrides.offsetDays ?? 1,
    dueTime: '09:00',
    skipWeekends: false,
  }
}

function fakeTx(steps: ReturnType<typeof step>[], pendingStepIds: string[] = []) {
  const tx = {
    task: {
      updateMany: jest.fn().mockResolvedValue({ count: 2 }),
      findMany: jest.fn().mockResolvedValue(pendingStepIds.map((cadenceStepId) => ({ cadenceStepId }))),
      createManyAndReturn: jest.fn(({ data }: { data: CreatedTask[] }) =>
        Promise.resolve(data.map((task, index) => ({ id: `t${index}`, title: task.title, type: 'ligacao', dueDate: task.dueDate }))),
      ),
    },
    stageCadenceStep: { findMany: jest.fn().mockResolvedValue(steps) },
  }
  return tx
}

const service = new CadencesService({} as PrismaService)
const lead = { id: 'lead-1', name: 'Maria da Silva', ownerId: 'broker-1' }
const base = { organizationId: 'org-1', lead, actorId: 'coord-1' }

function run(tx: ReturnType<typeof fakeTx>, fromStageId: string | null, toStageId: string | null) {
  return service.applyOnStageChange(tx as unknown as Prisma.TransactionClient, { ...base, fromStageId, toStageId })
}

describe('CadencesService.applyOnStageChange', () => {
  it('cancels only pending automatic tasks from other stages and creates the new ones for the owner', async () => {
    const tx = fakeTx([step('s1'), step('s2', { offsetDays: 3 })])
    const result = await run(tx, 'qualificacao', 'simulacao')

    const cancelWhere = tx.task.updateMany.mock.calls[0][0].where
    expect(cancelWhere).toMatchObject({ leadId: 'lead-1', status: 'pendente', autoGenerated: true })
    expect(cancelWhere.OR).toEqual([{ cadenceStageId: null }, { cadenceStageId: { not: 'simulacao' } }])

    const created = tx.task.createManyAndReturn.mock.calls[0][0].data as CreatedTask[]
    expect(created.map((task) => task.assignedTo)).toEqual(['broker-1', 'broker-1'])
    expect(created[0].title).toBe('Ligar para Maria')
    expect(result.cancelled).toBe(2)
    expect(result.created).toHaveLength(2)
  })

  it('does not cancel anything when the stage stays the same, and skips steps already pending', async () => {
    const tx = fakeTx([step('s1'), step('s2')], ['s1'])
    const result = await run(tx, 'simulacao', 'simulacao')

    expect(tx.task.updateMany).not.toHaveBeenCalled()
    const created = tx.task.createManyAndReturn.mock.calls[0][0].data as CreatedTask[]
    expect(created.map((task) => task.cadenceStepId)).toEqual(['s2'])
    expect(result.cancelled).toBe(0)
  })

  it('creates nothing when every step is already pending', async () => {
    const tx = fakeTx([step('s1')], ['s1'])
    const result = await run(tx, 'simulacao', 'simulacao')
    expect(tx.task.createManyAndReturn).not.toHaveBeenCalled()
    expect(result.created).toEqual([])
  })

  it('only cancels when the lead leaves the funnel (lost)', async () => {
    const tx = fakeTx([step('s1')])
    const result = await run(tx, 'negociacao', null)

    expect(tx.task.updateMany.mock.calls[0][0].where.OR).toBeUndefined()
    expect(tx.stageCadenceStep.findMany).not.toHaveBeenCalled()
    expect(result).toEqual({ created: [], cancelled: 2 })
  })

  it('assigns to the actor when the lead has no owner', async () => {
    const tx = fakeTx([step('s1')])
    await service.applyOnStageChange(tx as unknown as Prisma.TransactionClient, {
      ...base,
      lead: { ...lead, ownerId: null },
      fromStageId: null,
      toStageId: 'contato',
    })
    const created = tx.task.createManyAndReturn.mock.calls[0][0].data as CreatedTask[]
    expect(created[0].assignedTo).toBe('coord-1')
  })

  it('reads only active steps of the target stage', async () => {
    const tx = fakeTx([])
    await run(tx, null, 'contato')
    expect(tx.stageCadenceStep.findMany.mock.calls[0][0].where).toEqual({
      organizationId: 'org-1',
      funnelStageId: 'contato',
      active: true,
    })
  })
})
