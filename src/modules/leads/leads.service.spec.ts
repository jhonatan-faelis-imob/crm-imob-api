import { NotFoundException } from '@nestjs/common'
import { PrismaService } from '../../prisma/prisma.service'
import { CadencesService } from '../cadences/cadences.service'
import { CreateLeadDto } from './dto/create-lead.dto'
import { LeadsService } from './leads.service'

type Stage = { id: string; name: string; orderIndex: number; organizationId: string }
type Step = {
  id: string
  organizationId: string
  funnelStageId: string
  title: string
  description: string | null
  type: string
  priority: string
  offsetDays: number
  dueTime: string
  skipWeekends: boolean
  orderIndex: number
  active: boolean
}
type LeadRow = { id: string; name: string; ownerId: string | null; funnelStageId: string | null; status: string }
type TaskRow = {
  id: string
  leadId: string
  assignedTo: string
  createdBy: string
  status: string
  autoGenerated: boolean
  cadenceStageId: string | null
  cadenceStepId: string | null
  title: string
  type: string
  dueDate: Date
}
type History = { leadId: string; fromStageId?: string | null; toStageId: string; toStageName: string }

function step(id: string, funnelStageId: string, title = 'Ligar para {{primeiro_nome}}'): Step {
  return {
    id,
    organizationId: 'org-1',
    funnelStageId,
    title,
    description: null,
    type: 'ligacao',
    priority: 'media',
    offsetDays: 1,
    dueTime: '09:00',
    skipWeekends: false,
    orderIndex: 0,
    active: true,
  }
}

// Banco em memória com só o que create e applyOnStageChange usam
function fakeDb(stages: Stage[], steps: Step[]) {
  const leads: LeadRow[] = []
  const tasks: TaskRow[] = []
  const history: History[] = []

  const stagesOf = (organizationId: string) =>
    stages.filter((stage) => stage.organizationId === organizationId).sort((a, b) => a.orderIndex - b.orderIndex)

  const db = {
    lead: {
      findMany: jest.fn().mockResolvedValue([]),
      findFirst: jest.fn().mockResolvedValue(null),
      create: jest.fn(({ data }: { data: CreateLeadDto & { ownerId: string; funnelStageId: string | null } }) => {
        const lead: LeadRow = {
          id: `lead-${leads.length + 1}`,
          name: data.name,
          ownerId: data.ownerId,
          funnelStageId: data.funnelStageId,
          status: 'novo',
        }
        leads.push(lead)
        const funnelStage = stages.find((stage) => stage.id === lead.funnelStageId) ?? null
        return Promise.resolve({ ...lead, funnelStage, owner: null, tags: [] })
      }),
    },
    funnelStage: {
      findFirst: jest.fn(({ where }: { where: { id?: string; organizationId: string } }) => {
        const list = stagesOf(where.organizationId)
        return Promise.resolve((where.id ? list.find((stage) => stage.id === where.id) : list[0]) ?? null)
      }),
    },
    stageCadenceStep: {
      count: jest.fn(({ where }: { where: { organizationId: string } }) =>
        Promise.resolve(steps.filter((item) => item.organizationId === where.organizationId).length),
      ),
      findMany: jest.fn(({ where }: { where: { funnelStageId: string } }) =>
        Promise.resolve(steps.filter((item) => item.funnelStageId === where.funnelStageId && item.active)),
      ),
    },
    leadStageHistory: {
      create: jest.fn(({ data }: { data: History }) => {
        history.push(data)
        return Promise.resolve(data)
      }),
    },
    task: {
      updateMany: jest.fn().mockResolvedValue({ count: 0 }),
      findMany: jest.fn(({ where }: { where: { leadId: string; cadenceStepId: { in: string[] } } }) =>
        Promise.resolve(
          tasks.filter(
            (task) =>
              task.leadId === where.leadId &&
              task.status === 'pendente' &&
              task.cadenceStepId !== null &&
              where.cadenceStepId.in.includes(task.cadenceStepId),
          ),
        ),
      ),
      createManyAndReturn: jest.fn(({ data }: { data: Omit<TaskRow, 'id' | 'status'>[] }) => {
        const rows = data.map((item) => ({ ...item, id: `task-${tasks.length + 1}`, status: 'pendente' }))
        tasks.push(...rows)
        return Promise.resolve(rows.map(({ id, title, type, dueDate }) => ({ id, title, type, dueDate })))
      }),
    },
  }
  // A transação roda as mesmas tabelas em memória
  const withTransaction = { ...db, $transaction: jest.fn((fn: (tx: typeof db) => Promise<unknown>) => fn(db)) }
  return { db: withTransaction, leads, tasks, history }
}

function setup(stages: Stage[], steps: Step[]) {
  const fake = fakeDb(stages, steps)
  const prisma = fake.db as unknown as PrismaService
  const service = new LeadsService(prisma, new CadencesService(prisma))
  return { ...fake, service }
}

const STAGES: Stage[] = [
  { id: 'stage-qualif', name: 'Qualificação', orderIndex: 1, organizationId: 'org-1' },
  { id: 'stage-novo', name: 'Novo', orderIndex: 0, organizationId: 'org-1' },
  { id: 'stage-vazia', name: 'Visita', orderIndex: 2, organizationId: 'org-1' },
  { id: 'stage-outra-org', name: 'Novo', orderIndex: -1, organizationId: 'org-2' },
]
const STEPS = [step('s-novo-1', 'stage-novo'), step('s-novo-2', 'stage-novo', 'Mandar mensagem'), step('s-qualif', 'stage-qualif')]

const broker = { id: 'broker-1', role: 'corretor', teamId: null }
const manager = { id: 'manager-1', role: 'gerente', teamId: null }

function dto(overrides: Partial<CreateLeadDto> = {}): CreateLeadDto {
  return { name: 'Maria da Silva', phone: '(11) 98888-7777', source: 'indicacao', intent: 'compra', ...overrides }
}

describe('LeadsService.create — cadência da etapa inicial', () => {
  it('sem funnelStageId, entra na etapa de menor orderIndex da organização e ganha as tarefas dela', async () => {
    const { service, tasks, history } = setup(STAGES, STEPS)
    const lead = await service.create('org-1', dto(), broker)

    expect(lead.funnelStageId).toBe('stage-novo')
    expect(history).toEqual([expect.objectContaining({ leadId: lead.id, toStageId: 'stage-novo', toStageName: 'novo' })])
    expect(tasks.map((task) => task.cadenceStepId)).toEqual(['s-novo-1', 's-novo-2'])
    expect(tasks.every((task) => task.autoGenerated && task.cadenceStageId === 'stage-novo')).toBe(true)
    expect(tasks[0].title).toBe('Ligar para Maria')
    expect(lead.cadence.created).toHaveLength(2)
    expect(lead.cadence.cancelled).toBe(0)
  })

  it('com funnelStageId explícito, ganha as tarefas daquela etapa', async () => {
    const { service, tasks } = setup(STAGES, STEPS)
    const lead = await service.create('org-1', dto({ funnelStageId: 'stage-qualif' }), broker)

    expect(lead.funnelStageId).toBe('stage-qualif')
    expect(tasks.map((task) => task.cadenceStepId)).toEqual(['s-qualif'])
    expect(lead.cadence.created).toHaveLength(1)
  })

  it('etapa de outra organização dá 404 e não cria nada', async () => {
    const { service, leads } = setup(STAGES, STEPS)
    await expect(service.create('org-1', dto({ funnelStageId: 'stage-outra-org' }), broker)).rejects.toBeInstanceOf(
      NotFoundException,
    )
    expect(leads).toHaveLength(0)
  })

  it('etapa sem passos cadastrados não cria tarefa e não quebra', async () => {
    const { service, tasks, history } = setup(STAGES, STEPS)
    const lead = await service.create('org-1', dto({ funnelStageId: 'stage-vazia' }), broker)

    expect(lead.funnelStageId).toBe('stage-vazia')
    expect(history).toHaveLength(1)
    expect(tasks).toHaveLength(0)
    expect(lead.cadence).toEqual({ created: [], cancelled: 0 })
  })

  it('organização sem etapas cria o lead sem etapa, sem histórico e sem cadência', async () => {
    const { service, tasks, history, db } = setup([], [])
    const lead = await service.create('org-1', dto(), broker)

    expect(lead.funnelStageId).toBeNull()
    expect(history).toHaveLength(0)
    expect(tasks).toHaveLength(0)
    expect(db.task.updateMany).not.toHaveBeenCalled()
    expect(lead.cadence).toEqual({ created: [], cancelled: 0 })
  })

  it('tarefas vão para o responsável do lead; sem responsável no corpo, para quem criou', async () => {
    const { service, tasks } = setup(STAGES, STEPS)
    await service.create('org-1', dto({ ownerId: 'broker-2' }), manager)
    await service.create('org-1', dto({ name: 'João', phone: '(11) 97777-6666' }), manager)

    expect(tasks.slice(0, 2).map((task) => task.assignedTo)).toEqual(['broker-2', 'broker-2'])
    expect(tasks.slice(2).map((task) => task.assignedTo)).toEqual(['manager-1', 'manager-1'])
    expect(tasks.every((task) => task.createdBy === 'manager-1')).toBe(true)
  })

  it('dois leads seguidos: cada um ganha as próprias tarefas, sem duplicar nem misturar', async () => {
    const { service, tasks } = setup(STAGES, STEPS)
    const first = await service.create('org-1', dto(), broker)
    const second = await service.create('org-1', dto({ name: 'João Souza', phone: '(11) 97777-6666' }), broker)

    expect(tasks).toHaveLength(4)
    expect(tasks.filter((task) => task.leadId === first.id).map((task) => task.cadenceStepId)).toEqual(['s-novo-1', 's-novo-2'])
    expect(tasks.filter((task) => task.leadId === second.id).map((task) => task.title)).toEqual([
      'Ligar para João',
      'Mandar mensagem',
    ])
    expect(second.cadence.created).toHaveLength(2)
  })
})
